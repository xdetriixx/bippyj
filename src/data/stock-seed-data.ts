const fiscalYears = ["FY2021", "FY2022", "FY2023", "FY2024", "FY2025"];
const fiscalQuarters = ["Q2 FY25", "Q3 FY25", "Q4 FY25", "Q1 FY26", "Q2 FY26"];

function trend(seed: number, base: number, vol: number): number[] {
  const out: number[] = [];
  let v = base;
  for (let i = 0; i < 30; i++) {
    const r = Math.sin(seed + i * 0.7) * vol + Math.cos(seed * 2 + i * 0.3) * vol * 0.5;
    v = Math.max(base * 0.85, Math.min(base * 1.15, v + r));
    out.push(Number(v.toFixed(2)));
  }
  return out;
}

function series(seed: number, base: number, growth: number) {
  return fiscalQuarters.map((period, i) => {
    const revenue = Math.max(1, Math.round(base + i * growth + Math.sin(seed + i) * base * 0.025));
    const margin = Math.max(3, Math.min(38, 16 + (seed % 8) * 1.6 + Math.cos(seed + i) * 2.2));
    return {
      period,
      revenue,
      netIncome: Math.round(revenue * (margin / 100)),
      margin: Number(margin.toFixed(1)),
    };
  });
}

function carbonSeries(seed: number, start: number, reduction: number) {
  return fiscalYears.map((period, i) => {
    const total = Math.max(
      2_000,
      Math.round((start - i * reduction * 2 + Math.sin(seed + i) * 1.2) * 1_000),
    );
    const scope1Share = 0.16 + (seed % 4) * 0.025;
    const scope2Share = 0.2 + (seed % 3) * 0.03;
    const scope1 = Math.round(total * scope1Share);
    const scope2 = Math.round(total * scope2Share);
    const scope3 = total - scope1 - scope2;
    return {
      period,
      scope1,
      scope2,
      scope3,
      total,
      intensity: Number((total / Math.max(1, start * 1_250 + i * 4_000)).toFixed(2)),
    };
  });
}

function energySeries(seed: number, renewableStart: number) {
  return fiscalYears.map((period, i) => {
    const renewable = Math.max(
      5,
      Math.min(98, renewableStart + i * 2.2 + Math.sin(seed + i) * 1.2),
    );
    return {
      period,
      renewable: Number(renewable.toFixed(1)),
      nonrenewable: Number((100 - renewable).toFixed(1)),
    };
  });
}

function esgTrendSeries(seed: number, start: number, drift: number) {
  return fiscalYears.map((period, i) => ({
    period,
    score: Math.max(
      0,
      Math.min(100, Math.round(start + i * drift * 2.2 + Math.sin(seed + i) * 1.2)),
    ),
  }));
}

